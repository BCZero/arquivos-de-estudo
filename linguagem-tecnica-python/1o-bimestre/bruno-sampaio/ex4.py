#Script Python contagem utilizando for

#Loop que conta de um a cem, um a um, iniciando em um e terminando em 100
print("Contagem de um a cem.")
for numero in range (1, 101, 1):
    print(numero)

#Loop que conta de zero a cem, dois a dois, iniciando em 02 e terminando em 100
print("Contagem dos números pares.")
for numero in range (0, 101, 2):
    print(numero)

print("Fim do código")